-- The game's popup with a box: the last one shown is kept, Answer() fills and accepts it.
POPUP = false
function StaticPopup_Show(which, text, _, data) POPUP = { which = which, text = text, data = data } end
local function Answer(value)
    if not Check(POPUP, "a box asks for a number") then return end
    local box = { GetText = function() return tostring(value) end, SetText = function() end, SetFocus = function() end }
    local dialog = { EditBox = box, data = POPUP.data }
    StaticPopupDialogs[POPUP.which].OnShow(dialog)
    POPUP = false
    StaticPopupDialogs["RPSHEET_FEATURE_AMOUNT"].OnAccept(dialog, dialog.data)
end
local function Use(name)
    local ability = Ability(name)
    if Check(ability, "the sheet has the ability " .. name) then RPSheet:UseAbility(ability) end
end
local function Sides(from)
    local list = {}
    for i = (from or 0) + 1, #ROLLED do list[#list + 1] = ROLLED[i].sides end
    return table.concat(list, ",")
end
local function SetHP(hp) RPSheet:State().hp = hp end

