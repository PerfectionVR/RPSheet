Section("Divine Intervention and Wish", function()
    Build("PRIEST", "Life Domain", 20)
    local intervention = Tracker("Divine Intervention")
    Use("Divine Intervention")
    Click(MENU, "Wish")
    Eq(intervention.get(), 0, "Wish spends Divine Intervention")
    local rests = RPSheet:State().interventionRests
    Check(type(rests) == "number" and rests >= 2 and rests <= 8, "2d4 long rests are rolled")
    for _ = 1, rests - 1 do RPSheet:LongRest() end
    Eq(intervention.get(), 0, "still spent before the last of them")
    RPSheet:LongRest()
    Eq(intervention.get(), 1, "back after the last")
    Use("Divine Intervention")
    Click(MENU, "5th level or lower")
    RPSheet:LongRest()
    Eq(intervention.get(), 1, "another spell is back after one long rest")
end)

Section("Memorize Spell", function()
    Build("MAGE", "", 5)
    local sheet = RPSheet:Sheet()
    local prepared, other = "Magic Missile", "Sleep"
    ns.SpellbookAdd(sheet, prepared)
    ns.SpellbookAdd(sheet, other)
    Check(RPSheet:PrepareSpell(prepared, true), "a spell of the book prepared")
    RPSheet:State().prepareClosed = true
    Check(not RPSheet:UnprepareSpell(prepared), "after a spell the list is fixed")
    RPSheet:ShortRest()
    Check(RPSheet:UnprepareSpell(prepared), "after a short rest one spell can be put away")
    Check(RPSheet:PrepareSpell(other), "...and another prepared in its place")
    Check(not RPSheet:UnprepareSpell(other), "only one")
    Build("MAGE", "", 4)
    RPSheet:State().prepareClosed = true
    RPSheet:ShortRest()
    Eq(RPSheet:State().memorizeSwap, nil, "not before level 5")
end)

Section("Dragon constellation", function()
    Build("DRUID", "Circle of the Stars", 3)
    Passive("Dragon").enabled = true
    Rolls(3)
    RPSheet:RollCheck("WIS check", 0, nil, false, {})
    Said("counts as 10", "a low Wisdom check counts as 10")
    Rolls(3)
    RPSheet:RollCheck("Arcana", 0, nil, false, {})
    Said("counts as 10", "an Intelligence skill too")
    Rolls(3)
    RPSheet:RollCheck("STR check", 0, nil, false, {})
    Check(not SENT[#SENT]:find("counts as 10", 1, true), "not a Strength check")
    RPSheet:State().conditions.Concentrating = true
    Rolls(2)
    RPSheet:RollConcentration(10, false)
    Said("counts as 10", "the save to keep concentrating")
    Passive("Dragon").enabled = false
    Rolls(3)
    RPSheet:RollCheck("WIS check", 0, nil, false, {})
    Check(not SENT[#SENT]:find("counts as 10", 1, true), "only while the Dragon is on")
end)

