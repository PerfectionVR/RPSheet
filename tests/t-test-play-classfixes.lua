Section("a use bought back", function()
    Build("PALADIN", "Oath of Devotion", 20)
    Use("Holy Nimbus")
    Eq(Tracker("Holy Nimbus").get(), 0, "Holy Nimbus spends its use")
    local slots = Slot(5).get()
    RPSheet:UseAbility(Ability("Holy Nimbus"))
    Eq(Slot(5).get(), slots - 1, "used again, Holy Nimbus spends a 5th-level slot")
    Said("5th-level slot", "the slot is named")
    Build("SHAMAN", "Path of the Berserker", 14)
    Use("Intimidating Presence")
    local rage = Tracker("Rage").get()
    Use("Intimidating Presence")
    Eq(Tracker("Rage").get(), rage - 1, "Intimidating Presence again spends a Rage use")
    Build("DRUID", "Circle of the Moon", 10, { base = { STR = 8, DEX = 12, CON = 14, INT = 10, WIS = 16, CHA = 10 } })
    Tracker("Moonlight Step").set(0)
    Slot(1).set(4)
    local second = Slot(2).get()
    Use("Moonlight Step")
    Eq(Slot(2).get(), second - 1, "Moonlight Step with no use left spends a slot of 2nd level, not 1st")
    Eq(Slot(1).get(), 4, "...and leaves the 1st-level slots")
    Build("WARLOCK", "Fiend Patron", 14)
    Tracker("Hurl Through Hell").set(0)
    local pact = Slot(5)
    local before = pact.get()
    Rolls(1, 1, 1, 1, 1, 1, 1, 1)
    Use("Hurl Through Hell")
    Eq(pact.get(), before - 1, "Hurl Through Hell again spends a pact slot")
    Build("EVOKER", "Draconic Sorcery", 14)
    Use("Dragon Wings")
    local points = Tracker("Sorcery Points").get()
    Use("Dragon Wings")
    Eq(Tracker("Sorcery Points").get(), points - 3, "Dragon Wings again costs 3 Sorcery Points")
end)

