Section("Lay on Hands and smites", function()
    Build("PALADIN", "Oath of Devotion", 5)
    local pool = Tracker("Lay on Hands")
    Eq(pool.get(), 25, "a level 5 pool")
    SetHP(10)
    Use("Lay on Hands")
    Check(MENU and MENU.title:find("Lay on Hands"), "Lay on Hands asks first")
    Click(MENU, "Heal yourself")
    Answer(7)
    Eq(pool.get(), 18, "7 points spent")
    Eq(HP(), 17, "7 hit points back on you")
    Use("Lay on Hands")
    Click(MENU, "Heal someone else")
    Answer(40)
    Eq(pool.get(), 0, "no more than the pool")
    Eq(HP(), 17, "healing someone else leaves your hit points")
    pool.set(5)
    Use("Lay on Hands")
    Click(MENU, "poisoned")
    Eq(pool.get(), 0, "ending poisoned costs 5")
    Build("PALADIN", "Oath of Devotion", 14)
    Use("Lay on Hands")
    Check(MENU and Click(MENU, "stunned"), "Restoring Touch ends stunned")
    local at = #ROLLED
    Use("Divine Smite")
    Click(MENU, "Yes")
    Eq(Sides(at), "8,8,8", "a smite on a fiend rolls 3d8")
    at = #ROLLED
    Use("Divine Smite")
    Click(MENU, "No")
    Eq(Sides(at), "8,8", "...and 2d8 on others")
end)

Section("runes", function()
    Build("DEATHKNIGHT", "Oath of the Ebon Blade", 20, { spec = "Blood" })
    SetHP(100)
    local strike = Spell("Rune Strike") or Learn("Rune Strike")
    Rolls(3, 4)
    RPSheet:CastSpell(strike)
    Click(MENU, "Another creature") -- the spell asks what it hit (Data/SpellVariants.lua)
    Eq(RPSheet.runeStrikeDamage, 7, "the Rune Strike's necrotic damage is remembered")
    Use("Runic Power")
    Check(POPUP and POPUP.text:find("necrotic"), "Blood Runic Power asks for the necrotic damage")
    Answer(7)
    Eq(HP(), 107 <= RPSheet:MaxHP() and 107 or RPSheet:MaxHP(), "Blood Runic Power heals by it")
    SetHP(100)
    Use("Runic Mastery")
    Eq(HP(), 80, "Blood Runic Mastery costs your level in hit points")
    local before = Tracker("Channel Divinity") and Slot(4).get()
    Use("Runic Mastery")
    Eq(Slot(4).get(), before, "without the Aspect no slot pays for Runic Mastery")
    Use("Aspect of the Horsemen")
    Check(Passive("Aspect of the Horsemen active").enabled, "the Aspect switches its passive on")
    local at = #ROLLED
    Use("Runic Mastery")
    Check(MENU and MENU.title:find("which rune"), "with the Aspect Runic Mastery asks which rune")
    Click(MENU, "Frost")
    Eq(Slot(4).get(), before - 1, "...and a 4th-level slot pays for it")
    Eq(Sides(at), "6,6,6,6,6,6,6,6", "the Frost effect rolls 8d6")
end)

